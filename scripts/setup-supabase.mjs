#!/usr/bin/env node
/*
 * ASIMETRIJA — one-shot Supabase setup.
 *
 * Run this ON YOUR OWN MACHINE (not the Claude Code web sandbox, whose network
 * policy blocks api.supabase.com). It uses your Personal Access Token to:
 *   1. create a new Supabase project (or reuse SUPABASE_PROJECT_REF)
 *   2. wait until it's healthy
 *   3. apply supabase/migrations/0001_init.sql (tables + RLS + realtime)
 *   4. read the anon key and write config.js (Project URL + anon key)
 *
 * Usage:
 *   export SUPABASE_ACCESS_TOKEN=sbp_xxx        # required (Account → Access Tokens)
 *   node scripts/setup-supabase.mjs
 *
 * Optional env:
 *   SUPABASE_PROJECT_REF   reuse an existing project instead of creating one
 *   SUPABASE_ORG_ID        org to create the project in (defaults to your first org)
 *   PROJECT_NAME           default "asimetrija"
 *   SUPABASE_REGION        default "eu-central-1"
 *   SUPABASE_DB_PASSWORD   default: a random strong password (printed once)
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { randomBytes } from "node:crypto";

const API = "https://api.supabase.com";
const TOKEN = process.env.SUPABASE_ACCESS_TOKEN;
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

if (!TOKEN) die("Set SUPABASE_ACCESS_TOKEN (sbp_...) first. See .env.example.");

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
function die(msg) { console.error("\n✗ " + msg); process.exit(1); }
function log(msg) { console.log(msg); }

async function api(path, init = {}) {
  const res = await fetch(API + path, {
    ...init,
    headers: {
      Authorization: `Bearer ${TOKEN}`,
      "Content-Type": "application/json",
      ...(init.headers || {}),
    },
  });
  const text = await res.text();
  let body; try { body = text ? JSON.parse(text) : null; } catch { body = text; }
  if (!res.ok) die(`${init.method || "GET"} ${path} → HTTP ${res.status}: ${typeof body === "string" ? body : JSON.stringify(body)}`);
  return body;
}

async function main() {
  let ref = process.env.SUPABASE_PROJECT_REF;

  if (!ref) {
    let orgId = process.env.SUPABASE_ORG_ID;
    if (!orgId) {
      const orgs = await api("/v1/organizations");
      if (!orgs?.length) die("No organizations on this account. Create one in the Supabase dashboard first.");
      orgId = orgs[0].id;
      log(`• Using organization: ${orgs[0].name} (${orgId})`);
    }
    const name = process.env.PROJECT_NAME || "asimetrija";
    const region = process.env.SUPABASE_REGION || "eu-central-1";
    const dbPass = process.env.SUPABASE_DB_PASSWORD || randomBytes(18).toString("base64url");
    log(`• Creating project "${name}" in ${region} …`);
    const proj = await api("/v1/projects", {
      method: "POST",
      body: JSON.stringify({ name, organization_id: orgId, region, db_pass: dbPass, plan: "free" }),
    });
    ref = proj.id || proj.ref;
    log(`• Project ref: ${ref}`);
    if (!process.env.SUPABASE_DB_PASSWORD) log(`• Generated DB password (save it): ${dbPass}`);
  } else {
    log(`• Reusing existing project: ${ref}`);
  }

  // wait until healthy
  log("• Waiting for the project to become healthy (can take 1–2 min) …");
  for (let i = 0; i < 60; i++) {
    const p = await api(`/v1/projects/${ref}`);
    if (p.status === "ACTIVE_HEALTHY") { log("• Project is healthy."); break; }
    if (i === 59) die(`Project did not become healthy (last status: ${p.status}).`);
    process.stdout.write(`  status: ${p.status}\r`);
    await sleep(5000);
  }

  // apply migration
  log("• Applying migrations/0001_init.sql …");
  const sql = await readFile(join(ROOT, "supabase/migrations/0001_init.sql"), "utf8");
  await api(`/v1/projects/${ref}/database/query`, { method: "POST", body: JSON.stringify({ query: sql }) });
  log("• Schema applied (app_state + tickets + RLS + realtime).");

  // fetch anon key
  log("• Reading anon key …");
  const keys = await api(`/v1/projects/${ref}/api-keys?reveal=true`);
  const anon =
    keys.find?.((k) => k.name === "anon")?.api_key ||
    keys.find?.((k) => k.type === "anon")?.api_key ||
    keys.find?.((k) => /anon|publishable/i.test(k.name || ""))?.api_key;
  if (!anon) die("Could not read the anon key from the API. Grab it from Dashboard → API Keys and edit config.js manually.");

  const url = `https://${ref}.supabase.co`;
  const configJs =
`/* Generated by scripts/setup-supabase.mjs — URL + anon key are public-safe (RLS protects data). */
window.ASIM_CONFIG = {
  url:     "${url}",
  anonKey: "${anon}",
};
`;
  await writeFile(join(ROOT, "config.js"), configJs);

  log("\n✓ Done.");
  log(`  Project URL : ${url}`);
  log(`  config.js   : written with URL + anon key`);
  log("\nNext:");
  log("  1) Create your single login user — Dashboard → Authentication → Users → Add user");
  log("     (set a password and tick 'Auto Confirm User').");
  log("  2) Open index.html, sign in once. Your plan + journal now sync to the cloud.");
  log(`  3) Desktop MCP: put ${ref} as YOUR_PROJECT_REF in claude_desktop_config.json.`);
}

main().catch((e) => die(e?.message || String(e)));
